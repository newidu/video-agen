#!/usr/bin/env node
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manifestPath = path.join(root, 'skills', 'manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
if (!Array.isArray(manifest.order) || manifest.order.length === 0) throw new Error('skills/manifest.json must contain a non-empty order array');
const files = {};
for (const relative of manifest.order) {
  if (typeof relative !== 'string' || relative.includes('..') || path.isAbsolute(relative)) throw new Error('Unsafe skill path: ' + relative);
  const absolute = path.join(root, 'skills', relative);
  if (!fs.existsSync(absolute) || !fs.statSync(absolute).isFile()) throw new Error('Missing skill file: ' + relative);
  files[relative] = fs.readFileSync(absolute, 'utf8').replace(/\r\n/g, '\n');
}
const output = [
  '/* Generated by scripts/build-skills.js from individual skill Markdown files. Do not edit by hand. */',
  'window.SKILL_FILES = ' + JSON.stringify(files) + ';',
  'window.SKILL_ORDER = ' + JSON.stringify(manifest.order) + ';',
  ''
].join('\n');
const destination = path.join(root, 'src', 'skills', 'skill-manifest.js');
fs.mkdirSync(path.dirname(destination), { recursive: true });
fs.writeFileSync(destination, output, 'utf8');
console.log(`Generated ${destination} (${manifest.order.length} skill files).`);
